/**
 * Returns Georgian description for an ICD-10 code.
 * Falls back to the provided English description or the code itself.
 */
export function getIcd10Ka(
  code: string | null | undefined,
  fallbackDescription?: string | null,
): string {
  if (!code) return fallbackDescription || "—";
  const ka = ICD10_KA[code.trim()];
  return ka || fallbackDescription || code;
}
